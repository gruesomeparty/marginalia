#!/usr/bin/env bash
# Says who wrote an issue comment: human, agent or other.
#
# Usage (what .github/workflows/triage.yml does):
#   jq -n --arg login "$LOGIN" --arg type "$TYPE" --arg body "$BODY" \
#         --argjson trusted '["gruesomeparty"]' \
#         '{login: $login, type: $type, body: $body, trusted: $trusted}' \
#     | scripts/comment-from.sh
#
# Berkay and the agents working for him post under the same GitHub account,
# so the login alone cannot tell them apart. An agent marks what it writes
# instead, and the mark is what this script reads:
#
#   agent   a bot account (the loops post as github-actions[bot]), or a body
#           carrying a hidden <!-- agent:… --> block or Claude Code's footer
#           ("Generated by/with [Claude Code]"), which every agent comment
#           already ends with
#   human   an unmarked comment by a trusted login (the repo owner plus
#           TRIAGE_TRUSTED)
#   other   an unmarked comment by anyone else — a person, but not one whose
#           comment may start a paid run
#
# The mark is a convention, not a credential: anyone can leave it off. That is
# why a trusted login is still required for "human", and why the only thing a
# "human" answer buys is a re-triage, which can still only touch the labels
# scripts/apply-triage.sh allows.
set -euo pipefail

jq -r '
  (.login // "") as $login
  | (.body // "") as $body
  | if (.type // "") == "Bot" or ($login | endswith("[bot]")) then "agent"
    elif ($body | test("<!--\\s*agent:")) then "agent"
    elif ($body | test("Generated (by|with) \\[?Claude Code"; "i")) then "agent"
    elif (.trusted // []) | index($login) then "human"
    else "other"
    end
'
