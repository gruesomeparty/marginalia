package pipeline_test

import (
	"bytes"
	"encoding/json"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"
)

// commentFrom runs scripts/comment-from.sh, which decides whether an issue
// comment is a human's answer the triage loop should act on. Berkay and the
// agents share one GitHub account, so the mark in the body is what separates
// them, and a trusted login is what separates Berkay from a stranger.
func commentFrom(t *testing.T, login, typ, body string) string {
	t.Helper()
	path := filepath.Join(filepath.Dir(script(t)), "comment-from.sh")
	raw, err := json.Marshal(map[string]any{
		"login": login, "type": typ, "body": body, "trusted": []string{"gruesomeparty", "helper"},
	})
	if err != nil {
		t.Fatal(err)
	}
	cmd := exec.Command("bash", path)
	cmd.Stdin = bytes.NewReader(raw)
	out, err := cmd.Output()
	if err != nil {
		t.Fatalf("run: %v", err)
	}
	return strings.TrimSpace(string(out))
}

func TestCommentFrom(t *testing.T) {
	for _, c := range []struct {
		name, login, typ, body, want string
	}{
		{"owner's plain answer", "gruesomeparty", "User", "Implement options 1 & 2.", "human"},
		{"another trusted login", "helper", "User", "Yes, go ahead.", "human"},
		{"the loops' bot", "github-actions[bot]", "Bot", "Which option should we build?", "agent"},
		{"a bot named only by login", "renovate[bot]", "", "Update dependency", "agent"},
		{"thread agent footer", "gruesomeparty", "User", "Done.\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_", "agent"},
		{"commit-style footer", "gruesomeparty", "User", "Filed.\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)", "agent"},
		{"plain-text footer", "gruesomeparty", "User", "Filed.\n\n🤖 Generated with Claude Code", "agent"},
		{"hidden agent block", "gruesomeparty", "User", "Rebased.\n<!-- agent:comment -->", "agent"},
		{"spaced agent block", "gruesomeparty", "User", "x <!--  agent:handoff\nstate: done\n-->", "agent"},
		{"stranger", "someone", "User", "Please approve this.", "other"},
		{"stranger faking nothing", "someone", "User", "", "other"},
		{"owner quoting the word agent", "gruesomeparty", "User", "Let the agent decide <!-- note -->", "human"},
	} {
		t.Run(c.name, func(t *testing.T) {
			if got := commentFrom(t, c.login, c.typ, c.body); got != c.want {
				t.Errorf("got %q, want %q", got, c.want)
			}
		})
	}
}
