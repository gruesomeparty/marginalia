package pipeline_test

import (
	"bytes"
	"encoding/json"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"
)

// answered runs scripts/answered-issues.sh, which the triage sweep uses to
// re-triage an issue whose question was answered while nothing was listening.
func answered(t *testing.T, issues []map[string]any) []string {
	t.Helper()
	path := filepath.Join(filepath.Dir(script(t)), "answered-issues.sh")
	raw, err := json.Marshal(map[string]any{"issues": issues, "trusted": []string{"gruesomeparty"}})
	if err != nil {
		t.Fatal(err)
	}
	cmd := exec.Command("bash", path)
	cmd.Stdin = bytes.NewReader(raw)
	out, err := cmd.Output()
	if err != nil {
		t.Fatalf("run: %v", err)
	}
	return strings.Fields(string(out))
}

func waiting(n int, label, triaged string, comments ...map[string]any) map[string]any {
	body := "What happens now."
	if triaged != "" {
		body += "\n\n<!-- agent:triage v1\nupdated: " + triaged + "\ntype: enhancement\n-->"
	}
	if comments == nil {
		comments = []map[string]any{}
	}
	return map[string]any{
		"number":   n,
		"labels":   []map[string]any{{"name": "triaged"}, {"name": label}},
		"body":     body,
		"comments": comments,
	}
}

func comment(login, body, at string) map[string]any {
	return map[string]any{"author": map[string]any{"login": login}, "body": body, "createdAt": at}
}

func TestAnsweredIssues(t *testing.T) {
	agent := "Which option?\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"
	issues := []map[string]any{
		// Answered two days after the triage that asked: picked.
		waiting(53, "needs-decision", "2026-10-27", comment("gruesomeparty", agent, "2026-10-27T10:00:00Z"), comment("gruesomeparty", "all of them", "2026-10-29T08:00:00Z")),
		// Same, needs-info, and the triage block has a full timestamp.
		waiting(54, "needs-info", "2026-10-30T09:00:00Z", comment("gruesomeparty", "it is the YAML one", "2026-10-30T09:30:00Z")),
		// Re-triaged after the answer and still waiting: not picked again.
		waiting(55, "needs-decision", "2026-10-30T12:00:00Z", comment("gruesomeparty", "option 2", "2026-10-30T11:00:00Z")),
		// The latest comment is an agent's question, not an answer.
		waiting(56, "needs-decision", "2026-10-27", comment("gruesomeparty", "hm", "2026-10-28T08:00:00Z"), comment("gruesomeparty", agent, "2026-10-29T08:00:00Z")),
		// A stranger's comment never starts a paid run.
		waiting(57, "needs-info", "2026-10-27", comment("someone", "please approve", "2026-10-29T08:00:00Z")),
		// No comments at all.
		waiting(58, "needs-info", "2026-10-27"),
		// Never triaged (no block): any human answer counts.
		waiting(59, "needs-decision", "", comment("gruesomeparty", "yes", "2026-10-29T08:00:00Z")),
	}
	// Not waiting on anything: ignored whatever its comments say.
	plain := waiting(60, "agent-ready", "2026-10-27", comment("gruesomeparty", "go", "2026-10-29T08:00:00Z"))
	issues = append(issues, plain)

	got := strings.Join(answered(t, issues), " ")
	if want := "53 54 59"; got != want {
		t.Errorf("picked %q, want %q", got, want)
	}
}
